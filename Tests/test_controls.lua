-- Motion and the remaining components (M7-1): the transitions of docs/specs/ui-style.md (120 / 200 / 320 ms, OUT), the
-- "Animations: off" preference, hover and pressed layers, the Switch, Slider, Select, Snackbar, Skeleton and class mark.

local function M() return FDCP.Motion end
local function W() return FDCP.Widgets end
local function groupOf(frame) return frame._animGroups and frame._animGroups[#frame._animGroups] end
local function first(group) return group._anims[1] end

describe("motion", function()
	it("the durations of the spec", function()
		eq(M().FAST, 0.12); eq(M().BASE, 0.2); eq(M().SLOW, 0.32)
		eq(M().PRESS, 0.97)
		eq(M().SMOOTHING, "OUT")
	end)

	it("Fade plays an alpha animation with the OUT curve and sets the end state when it finishes", function()
		local f = CreateFrame("Frame")
		f:SetAlpha(0.2)
		truthy(M().Fade(f, 1, M().BASE))
		local g = groupOf(f)
		truthy(g:IsPlaying())
		local a = first(g)
		eq(a._kind, "Alpha")
		eq(a:GetDuration(), 0.2); eq(a:GetSmoothing(), "OUT")
		eq(a:GetFromAlpha(), 0.2); eq(a:GetToAlpha(), 1)
		Mock.FinishAnimations()
		eq(f:GetAlpha(), 1)
	end)

	it("one group is reused for every fade of a region", function()
		local f = CreateFrame("Frame")
		M().Fade(f, 1, 0.2); M().Fade(f, 0, 0.2); M().Fade(f, 1, 0.2)
		eq(#f._animGroups, 1)
	end)

	it("with Animations off every call ends at once and nothing is played", function()
		FDCP.Config:Set("animations", false)
		falsy(M().On())
		local f = CreateFrame("Frame")
		local ran = false
		falsy(M().Fade(f, 0.5, 0.2, function() ran = true end))
		eq(f:GetAlpha(), 0.5); truthy(ran)
		falsy(f._animGroups)
		local t = CreateFrame("Frame"):CreateTexture()
		falsy(M().Rotate(t, 1.5, 0.32))
		eq(t._rotation, nil)
		FDCP.Config:Set("animations", true)
		truthy(M().On())
	end)

	it("FadeIn shows a hidden region from 0 and FadeOut hides it at the end", function()
		local f = CreateFrame("Frame")
		f:Hide()
		M().FadeIn(f, 0.2)
		truthy(f:IsShown()); eq(f:GetAlpha(), 0)
		Mock.FinishAnimations()
		eq(f:GetAlpha(), 1)
		M().FadeOut(f, 0.2)
		Mock.FinishAnimations()
		falsy(f:IsShown()); eq(f:GetAlpha(), 1)
	end)

	it("Rise moves a panel up while it fades in and puts it back at its anchor", function()
		local f = CreateFrame("Frame")
		f:SetPoint("CENTER", UIParent, "CENTER", 0, 0)
		truthy(M().Rise(f, 16, M().SLOW))
		local _, _, _, x, y = f:GetPoint(1)
		eq(y, -16)
		local g = groupOf(f)
		eq(g._anims[2]:GetOffset(), 0)
		eq(g._anims[1]:GetDuration(), 0.32)
		Mock.FinishAnimations()
		_, _, _, x, y = f:GetPoint(1)
		eq(y, 0); eq(f:GetAlpha(), 1)
	end)

	it("a turn ends at its angle", function()
		local t = CreateFrame("Frame"):CreateTexture()
		M().Rotate(t, 0, 0)
		truthy(M().Rotate(t, math.pi / 2, M().SLOW))
		eq(first(groupOf(t))._kind, "Rotation")
		Mock.FinishAnimations()
		eq(t._rotation, nil)
		falsy(M().Rotate(t, math.pi / 2, M().SLOW))   -- already there
	end)

	it("Slide places the region at the end of the movement", function()
		local f = CreateFrame("Frame")
		local at
		truthy(M().Slide(f, 18, 0, M().BASE, function(dx) at = dx end))
		eq(at, nil)
		Mock.FinishAnimations()
		eq(at, 18)
	end)

	it("a pulse repeats while shown and rests at the middle with animations off", function()
		local f = CreateFrame("Frame")
		local p = M().Pulse(f, 0.3, 1, 0.9)
		p.Start()
		eq(groupOf(f):GetLooping(), "BOUNCE"); truthy(groupOf(f):IsPlaying())
		FDCP.Config:Set("animations", false)
		p.Start()
		falsy(groupOf(f):IsPlaying())
		near(f:GetAlpha(), 0.65, 1e-9)
	end)
end)

describe("button states", function()
	local function button(style)
		return W().Button(CreateFrame("Frame"), { text = "Go", style = style })
	end

	it("hover lays 8 % white, pressed 12 %, both faded in 120 ms", function()
		local b = button()
		Mock.RunScript(b, "OnEnter")
		eq(first(groupOf(b.over)):GetToAlpha(), 0.08)
		eq(first(groupOf(b.over)):GetDuration(), 0.12)
		Mock.RunScript(b, "OnMouseDown")
		eq(first(groupOf(b.over)):GetToAlpha(), 0.12)
		Mock.RunScript(b, "OnMouseUp")
		eq(first(groupOf(b.over)):GetToAlpha(), 0.08)   -- still over it
		Mock.RunScript(b, "OnLeave")
		eq(first(groupOf(b.over)):GetToAlpha(), 0)
	end)

	it("a disabled button dims and shows no hover", function()
		local b = button()
		b:SetEnabled(false)
		near(b:GetAlpha(), 0.45, 1e-9)
		Mock.RunScript(b, "OnEnter")
		eq(first(groupOf(b.over)):GetToAlpha(), 0)
		b:SetEnabled(true)
		eq(b:GetAlpha(), 1)
	end)

	it("a press shrinks the button to 0.97 in 120 ms and releases it in 120 ms", function()
		local b = button("primary")
		Mock.RunScript(b, "OnMouseDown")
		local down, up = b._animGroups[1], b._animGroups[2]
		truthy(down:IsPlaying())
		local s = first(down)
		eq(s._kind, "Scale"); eq(s:GetDuration(), 0.12); eq(s:GetSmoothing(), "OUT")
		eq(select(1, s:GetScaleTo()), 0.97)
		Mock.RunScript(b, "OnMouseUp")
		falsy(down:IsPlaying()); truthy(up:IsPlaying())
		eq(select(1, first(up):GetScaleTo()), 1)
	end)

	it("no press animation with Animations off", function()
		FDCP.Config:Set("animations", false)
		local b = button()
		Mock.RunScript(b, "OnMouseDown")
		falsy(b._animGroups[1]:IsPlaying())
	end)

	it("the primary and the neon buttons have a glow, the others none", function()
		truthy(button("primary").glow); truthy(button("neon").glow)
		falsy(button("secondary").glow); falsy(button("ghost").glow)
	end)
end)

describe("switch", function()
	it("toggles on click, reports the change and slides the thumb", function()
		local seen
		local s = W().Switch(CreateFrame("Frame"), { onChange = function(on) seen = on end })
		falsy(s:IsOn())
		Mock.RunScript(s, "OnClick")
		truthy(s:IsOn()); eq(seen, true)
		eq(first(groupOf(s.thumb))._kind, "Translation")
		eq(first(groupOf(s.thumb)):GetOffset(), 18)
		Mock.FinishAnimations()
		local _, _, _, x = s.thumb:GetPoint(1)
		eq(x, 22)
		Mock.RunScript(s, "OnClick")
		falsy(s:IsOn()); eq(seen, false)
	end)

	it("SetOn with silent does not call back, and a disabled switch ignores clicks", function()
		local n = 0
		local s = W().Switch(CreateFrame("Frame"), { onChange = function() n = n + 1 end })
		s:SetOn(true, true)
		eq(n, 0); truthy(s:IsOn())
		s:SetEnabled(false)
		Mock.RunScript(s, "OnClick")
		truthy(s:IsOn()); eq(n, 0)
	end)

	it("starts on when asked and takes the accent", function()
		local s = W().Switch(CreateFrame("Frame"), { on = true })
		truthy(s:IsOn())
		near((s.track:GetVertexColor()), 0xFC / 255, 1e-6)
	end)
end)

describe("slider", function()
	it("rounds to the step, clamps, and reports a user change", function()
		local got
		local s = W().Slider(CreateFrame("Frame"), { min = 0, max = 10, step = 2, value = 3, onChange = function(v, user) got = { v, user } end })
		eq(s:GetValue(), 4)
		s:Set(99); eq(s:GetValue(), 10)
		s:Set(-5); eq(s:GetValue(), 0)
		Mock.RunScript(s, "OnValueChanged", 6, true)
		deepEq(got, { 6, true })
	end)
end)

describe("select", function()
	local function make(onSelect)
		return W().Select(CreateFrame("Frame"), { width = 160, onSelect = onSelect, placeholder = "Pick",
			choices = { { id = "a", text = "Alpha" }, { id = "b", text = "Beta" } } })
	end

	it("shows the placeholder, opens a list on click and closes on a second click", function()
		local s = make()
		eq(s.label:GetText(), "Pick")
		Mock.RunScript(s, "OnClick")
		truthy(s:IsOpen())
		Mock.RunScript(s, "OnClick")
		falsy(s:IsOpen())
	end)

	it("choosing closes the list, shows the text and calls back once", function()
		local n, got = 0
		local s = make(function(id) n = n + 1; got = id end)
		s:Open()
		truthy(s:Select("b"))
		falsy(s:IsOpen())
		eq(s.label:GetText(), "Beta"); eq(got, "b")
		s:Select("b"); eq(n, 1)
		falsy(s:Select("zzz"))
	end)

	it("a click outside (the catcher) closes it, and it does not use UIDropDownMenu", function()
		local s = make()
		s:Open()
		Mock.RunScript(s.catcher, "OnClick")
		falsy(s:IsOpen())
		falsy(s.popup._template)
		eq(rawget(_G, "UIDropDownMenu_Initialize"), nil)
	end)

	it("the arrow turns while it opens", function()
		local s = make()
		s:Open()
		eq(first(groupOf(s.arrow))._kind, "Rotation")
	end)

	it("an empty list does not open", function()
		local s = W().Select(CreateFrame("Frame"), { choices = {} })
		s:Open()
		falsy(s:IsOpen())
	end)
end)

describe("snackbar", function()
	it("shows the text with the tone, fades in and goes away after 4 s", function()
		local host = CreateFrame("Frame")
		local sb = W().Snackbar(host)
		falsy(sb:IsShown())
		sb:Say("Saved", "ok")
		truthy(sb:IsShown()); eq(sb:Message(), "Saved")
		near((sb.dot:GetVertexColor()), 0x46 / 255, 1e-6)
		Mock.FinishAnimations()
		Mock.Advance(4.1)
		Mock.FinishAnimations()
		falsy(sb:IsShown())
	end)

	it("a newer message is not cut short by the timer of the older one", function()
		local sb = W().Snackbar(CreateFrame("Frame"))
		sb:Say("One", "ok", 4)
		Mock.Advance(3)
		sb:Say("Two", "err", 4)
		Mock.Advance(2)
		Mock.FinishAnimations()
		truthy(sb:IsShown()); eq(sb:Message(), "Two")
	end)

	it("the main window offers it as a toast", function()
		FDCP.MainWindow:Open()
		FDCP.MainWindow:Toast("Hello", "warn")
		truthy(FDCP.MainWindow.snackbar:IsShown())
	end)
end)

describe("skeleton and class mark", function()
	it("a skeleton pulses while shown and stops when hidden", function()
		local sk = W().Skeleton(CreateFrame("Frame"), 100, 12)
		Mock.RunScript(sk, "OnShow")
		truthy(groupOf(sk):IsPlaying())
		Mock.RunScript(sk, "OnHide")
		falsy(groupOf(sk):IsPlaying())
	end)

	it("the class mark is the colour of the class with a glow of the same colour", function()
		local f = CreateFrame("Frame")
		local m = W().ClassMark(f)
		W().PaintClassMark(m, 0.25, 0.78, 0.92)
		near(m._texture[1], 0.25, 1e-6)
		near((m.glow:GetVertexColor()), 0.25, 1e-6)
		truthy(m.glow._glow)
	end)
end)
